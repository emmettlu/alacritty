impl NamedKey {
    pub fn to_text(self) -> Option<&'static str> {
        match self {
            Self::Enter => Some("\r"),
            Self::Tab => Some("\t"),
            Self::Space => Some(" "),
            Self::Backspace => Some("\x08"),
            Self::Escape => Some("\x1b"),
            _ => None,
        }
    }
}
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Key<S = String> {
    Named(NamedKey),
    Character(S),
    Dead(Option<char>),
    Unidentified(NativeKey),
}
impl<S: AsRef<str>> Key<S> {
    pub fn as_ref(&self) -> Key<&str> {
        match self {
            Self::Named(n) => Key::Named(*n),
            Self::Character(s) => Key::Character(s.as_ref()),
            Self::Dead(c) => Key::Dead(*c),
            Self::Unidentified(n) => Key::Unidentified(*n),
        }
    }
}
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum NativeKey {
    #[default]
    Unidentified,
    Code(u32),
}
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PhysicalKey(pub u32);
impl PhysicalKey {
    pub fn from_scancode(code: u32) -> Self {
        Self(code)
    }
}
pub type KeyCode = PhysicalKey;
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum KeyLocation {
    #[default]
    Standard,
    Left,
    Right,
    Numpad,
}
bitflags::bitflags! {
    #[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
    pub struct ModifiersState: u8 { const SHIFT=1; const CONTROL=2; const ALT=4; const SUPER=8; }
}
impl ModifiersState {
    pub fn shift_key(self) -> bool {
        self.contains(Self::SHIFT)
    }
    pub fn control_key(self) -> bool {
        self.contains(Self::CONTROL)
    }
    pub fn alt_key(self) -> bool {
        self.contains(Self::ALT)
    }
    pub fn super_key(self) -> bool {
        self.contains(Self::SUPER)
    }
}
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModifiersKeyState {
    Pressed,
    Unknown,
}
